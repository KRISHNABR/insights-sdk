# --------------------------------------------------------------------------------
# The container image — rendered, never stored in a tenant repo
# --------------------------------------------------------------------------------

#: The trade-off, stated because it is a real fork. Generating a Dockerfile INTO the
#: tenant's repository would make it visible and independently buildable, which is worth
#: something. It would also make it EDITABLE — and the moment a team edits it, "runs as
#: non-root", "built on a supported base" and "SDK matches the manifest" stop being true
#: and become things CI has to check. Checking is weaker than knowing.
#:
#: So it stays platform-owned, and `insights build --show` prints it. Nothing is hidden;
#: nothing can drift.
DOCKERFILE = """\
# Rendered by `insights build` from app.yaml. NOT stored in the tenant repo.
#   app:  {name}
#   base: {base}
#
# Everything below is a consequence of what was declared. To change it, change
# app.yaml or pyproject.toml - and if neither can express what you need, that is a
# platform gap and we treat it as a bug rather than a request to work around (ADR-004).
FROM insights-hub/{base}:{base_version}

# Your dependencies, from YOUR pyproject.toml, installed from the COMMITTED lockfile.
# --frozen means the lock must already be current: the image resolves exactly what your
# laptop resolved, or the build fails. "Works on my machine" is not debuggable by a
# platform team of three.
#
# Copied before your source so a code change does not reinstall the world.
COPY pyproject.toml uv.lock ./
RUN uv sync --frozen --no-dev --no-install-project
{extra_system}
COPY src/ /app/src/
COPY app.yaml /app/app.yaml
{extra_static}"""

#: The published family and their pinned versions. `insights runtimes` reads this.
BASE_VERSIONS = {
    "python-web": "0.1",
    "python-data": "0.1",
    "python-min": "0.1",
    "python-streamlit": "0.1",
}


def render_dockerfile(manifest) -> str:
    """Render the image definition for an app, from what it declared.

    Three sources, and the split is the point:

      runtime.base           the platform's runtime and the SDK   (ours)
      pyproject.toml         the app's Python dependencies        (yours)
      runtime.system_packages  apt-level needs, e.g. libgeos      (yours, declared)

    A team never chooses a base OS, a Python version or a user id - but they own their
    own dependency list, exactly as they would in any Python project. That is what
    "bring your code" has to mean, or the platform is a cage.
    """
    system = tuple(getattr(manifest, "system_packages", ()) or ())
    extra_system = (
        "\n# runtime.system_packages from app.yaml - the long tail, without a bespoke image\n"
        "USER root\n"
        f"RUN apt-get update && apt-get install -y --no-install-recommends {' '.join(system)} \\\n"
        "    && rm -rf /var/lib/apt/lists/*\n"
        "USER insights\n"
        if system
        else ""
    )
    extra_static = (
        "COPY static/ /app/static/\n"
        if manifest.web is not None and manifest.web.type == "spa"
        else ""
    )
    return DOCKERFILE.format(
        name=manifest.app,
        base=manifest.base,
        base_version=BASE_VERSIONS.get(manifest.base, "0.1"),
        extra_system=extra_system,
        extra_static=extra_static,
    )


# --------------------------------------------------------------------------------
# Generation
# --------------------------------------------------------------------------------

#: Files the PLATFORM owns inside a tenant repository, re-rendered by
#: `insights upgrade-scaffold`. Everything else in a tenant repo is the tenant's.
#: The machine-readable version of "you own your code, we own the road it travels on".
#: Note the Dockerfile is absent — it is not in the tenant repo at all.
PLATFORM_OWNED = (
    Path(".github/workflows/ci.yml"),
    Path(".github/workflows/deploy-dev.yml"),
    Path(".github/workflows/deploy-uat.yml"),
    Path(".github/workflows/deploy-prod.yml"),
)


def render_platform_owned(name: str) -> dict[Path, str]:
    return {
        Path(".github/workflows/ci.yml"): CI.format(name=name),
        Path(".github/workflows/deploy-dev.yml"): DEPLOY_DEV.format(name=name),
        Path(".github/workflows/deploy-uat.yml"): DEPLOY_UAT.format(name=name),
        Path(".github/workflows/deploy-prod.yml"): DEPLOY_PROD.format(name=name),
    }


def generate(*, target: Path, name: str, kind: str, team: str, owner: str) -> list[Path]:
    if target.exists() and any(target.iterdir()):
        raise SystemExit(f"{target} already exists and is not empty")

    base = "python-web" if kind == "web" else "python-data"
    kind_block = (WEB_BLOCK if kind == "web" else JOB_BLOCK).format(name=name)

    files: dict[Path, str] = {
        Path("app.yaml"): MANIFEST.format(
            name=name, team=team, kind=kind, owner=owner, base=base, kind_block=kind_block
        ),
        Path("pyproject.toml"): PYPROJECT.format(name=name),
        Path("src/main.py"): (JOB_MAIN if kind == "job" else WEB_MAIN).format(name=name),
        Path("README.md"): README.format(name=name, kind=kind, team=team),
        Path(".gitignore"): GITIGNORE,
    }
    files.update(render_platform_owned(name))

    written = []
    for relative, content in files.items():
        path = target / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        written.append(path)
    return written
