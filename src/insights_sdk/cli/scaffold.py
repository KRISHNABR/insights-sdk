"""The generator — the cheapest enforcement layer the platform has.

ADR-004's rule is "enforce at the earliest layer that makes a rule impossible to get
wrong", and generation is the earliest layer there is: a CI pipeline that is generated
correctly cannot be a CI pipeline someone got wrong.

Templates live in the SDK, next to the library they scaffold, so the two versions can
never skew. And they are GENERATED, not cloned from a template repo: an app created
eighteen months ago carries an eighteen-month-old scaffold with nothing to tell anyone,
which is exactly the failure ADR-001 is about. `insights upgrade-scaffold` re-renders
exactly the files listed in PLATFORM_OWNED and touches nothing else.
"""

from __future__ import annotations

from pathlib import Path

